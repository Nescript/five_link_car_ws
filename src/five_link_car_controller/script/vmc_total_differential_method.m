% =========================================================
% 五连杆雅可比矩阵推导（全微分法）
% 符号定义与 README 第2节完全一致：
%
%   连杆拓扑：A -l1- B -l2- C -l3- D -l4- E
%   A = (0, 0)          左电机（坐标原点）
%   E = (l5, 0)         右电机
%   B = 左肘关节
%   D = 右肘关节
%   C = 末端（足端）
%
%   驱动角（输入）：
%     phi1：l1 与 x 轴正方向的夹角（左曲柄 A→B），逆时针为正
%     phi4：l4 与 x 轴正方向的夹角（右曲柄 E→D），逆时针为正
%
%   从动角（由约束确定）：
%     phi2：l2 与 x 轴正方向的夹角（左连杆 B→C），逆时针为正
%     phi3：l3 与 x 轴正方向的夹角（右连杆 D→C），逆时针为正
%
%   约束方程（README 式3）：C点由左链和右链表达相等
%     fx = l1*cos(phi1) + l2*cos(phi2) - (l5 + l4*cos(phi4) + l3*cos(phi3)) = 0
%     fy = l1*sin(phi1) + l2*sin(phi2) - (       l4*sin(phi4) + l3*sin(phi3)) = 0
% =========================================================

syms l1 l2 l3 l4 l5 real
syms phi1 phi4 phi2 phi3 real   % README 的符号命名

% ----------------------------------------------------------
% 1. 位置约束方程 f = [fx; fy] = 0
%    左链末端 C = 右链末端 C （README 式3）
% ----------------------------------------------------------
fx = l1*cos(phi1) + l2*cos(phi2) - (l5 + l4*cos(phi4) + l3*cos(phi3));
fy = l1*sin(phi1) + l2*sin(phi2) - (       l4*sin(phi4) + l3*sin(phi3));
f  = [fx; fy];

% ----------------------------------------------------------
% 2. 驱动变量 q（输入） 和 从动变量 th（由约束决定）
%    对应 README：phi1, phi4 为已知输入；phi2, phi3 为待求
% ----------------------------------------------------------
q  = [phi1; phi4];   % 驱动角（README：左右曲柄角）
th = [phi2; phi3];   % 从动角（README：左右连杆角）

% ----------------------------------------------------------
% 3. 隐函数偏导数矩阵
%    ∂f/∂q  (2×2)：约束方程对驱动角的偏导
%    ∂f/∂th (2×2)：约束方程对从动角的偏导
% ----------------------------------------------------------
fq  = jacobian(f, q);    % ∂f/∂q
fth = jacobian(f, th);   % ∂f/∂th

% 奇异性检验（det=0 时机构处于奇异位形，雅可比无意义）
det_fth = simplify(det(fth));
disp('det(∂f/∂th) = ');
disp(det_fth);

% ----------------------------------------------------------
% 4. 从动角对驱动角的导数矩阵
%    隐函数求导：dth/dq = -inv(fth) * fq
%    即 d[phi2;phi3]/d[phi1;phi4]
% ----------------------------------------------------------
dth_dq = -fth \ fq;   % 用 \ 代替 inv() 以提高数值稳定性

% ----------------------------------------------------------
% 5. 末端 C 点坐标（README 式2，用左链表示）
%    C = B + (l2*cos(phi2), l2*sin(phi2))
%      = (l1*cos(phi1) + l2*cos(phi2),
%         l1*sin(phi1) + l2*sin(phi2))
% ----------------------------------------------------------
xC = l1*cos(phi1) + l2*cos(phi2);   % README: x_c
yC = l1*sin(phi1) + l2*sin(phi2);   % README: y_c
C  = [xC; yC];

% ----------------------------------------------------------
% 6. C 点坐标对各变量的偏导
% ----------------------------------------------------------
Cq  = jacobian(C, q);    % ∂C/∂[phi1,phi4]
Cth = jacobian(C, th);   % ∂C/∂[phi2,phi3]

% ----------------------------------------------------------
% 7. 末端雅可比矩阵 J（2×2）
%    由全微分法：
%      dC/dt = ∂C/∂q * dq/dt + ∂C/∂th * dth/dt
%            = (∂C/∂q + ∂C/∂th * dth/dq) * dq/dt
%            = J * [dphi1/dt; dphi4/dt]
%
%    物理含义：J 将驱动角速度映射到末端 C 点的线速度
%      [vx_C; vy_C] = J * [phi1_dot; phi4_dot]
% ----------------------------------------------------------
J = Cq + Cth * dth_dq;
J = simplify(J);

disp('末端 C 点雅可比矩阵 J（符号结果）：');
disp(J);

% ----------------------------------------------------------
% 8. 数值验证（参数来自 config/five_link_car.yaml）
%    代入一组合理的工作姿态验证结果量级是否正确
% ----------------------------------------------------------
num_val = [l1,   l2,   l3,   l4,   l5,   phi1,     phi4,      phi2,    phi3   ];
num_num = [0.14, 0.25, 0.25, 0.14, 0.12, 3*pi/4,   pi/4,      pi/2,    pi/2   ];
%                                         ↑左曲柄    ↑右曲柄    ↑左连杆  ↑右连杆
%                                         135°       45°        90°      90°

J_num = double(subs(J, num_val, num_num));
disp('数值雅可比 J_num（该工作点处）：');
disp(J_num);

% 条件数检验（条件数大说明接近奇异）
disp('J 的条件数：');
disp(cond(J_num));